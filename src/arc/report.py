"""reports/EVALUATION.md, written from the JSON reports so the numbers in it are the ones measured."""

from __future__ import annotations

import json
from typing import Any

from arc.config import REPORTS


def _read(name: str) -> Any:
    p = REPORTS / name
    return json.loads(p.read_text()) if p.exists() else None


def _pct(x: float | None, d: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def _pp(x: float) -> str:
    return f"{100 * x:+.1f}pp"


def write_report(profile: str = "full") -> str:
    L: list[str] = [
        "# Evaluation",
        "",
        f"Generated by `arc run` (profile `{profile}`). Every number here comes from the JSON files next to this one.",
        "",
    ]
    rel = _read("releases.json")
    if rel:
        L += [
            "## What each release really does",
            "",
            "Same conversations for every release. *Observed* is what a support team can measure; *true* comes from the simulator and is never available to the shipping process.",
            "",
        ]
        L += [
            "| Release | Observed resolution | True resolution | True hallucination | Unsafe actions | Cost / conv. | p95 latency |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in rel:
            L.append(
                f"| {r['release']} | {_pct(r['resolution_observed'])} | {_pct(r['true_resolved'])} | {_pct(r['true_hallucinated'])} | {r['true_unsafe']} | €{r['cost_per_conversation_eur']:.4f} | {r['latency_p95_s']:.1f}s |"
            )
        L.append("")
    card = _read("model_card.json")
    if card:
        v = card["judge"]["validation"]
        L += [
            "## Judges",
            "",
            f"The learned judge was trained on {card['judge']['reviewed_conversations']:,} human-reviewed conversations of `r1-prod`, then checked on new conversations of the release it was trained on and of a different one.",
            "",
        ]
        L += ["| Conversations from | Judge | AUC | Judged rate | Labelled rate |", "|---|---|---|---|---|"]
        for rid, m in v.items():
            for k, x in m.items():
                L.append(f"| {rid} | {k} | {x['auc']:.3f} | {_pct(x['judged_rate'])} | {_pct(x['labelled_rate'])} |")
        L += [
            "",
            "A judge that works on production can be wrong on a candidate that changes what kind of mistakes the agent makes. Backtests therefore correct judge scores with human labels on a random sample (prediction-powered inference) instead of trusting them.",
            "",
        ]
    revs = sorted((REPORTS / "reviews").glob("*.json")) if (REPORTS / "reviews").exists() else []
    if revs:
        L += [
            "## Release reviews",
            "",
            "| Release | Decision | Stopped at | Why | Eval cost | Calendar days |",
            "|---|---|---|---|---|---|",
        ]
        for p in revs:
            r = json.loads(p.read_text())
            L.append(
                f"| [{r['candidate']}](reviews/{r['candidate']}.md) | {r['decision']} | {r['stopped_at'] or ''} | {'; '.join(r['reasons'])[:160]} | €{r['eval_cost_eur']:.0f} | {r['calendar_days']} |"
            )
        L.append("")
    aa = _read("aa_test.json")
    if aa:
        L += [
            "## A/A test",
            "",
            f"Production against itself for {aa['plan']['days']} days: {aa['decision']} (difference {_pp(aa['primary']['diff'])}, p = {aa['primary']['p']:.3f}, sample-ratio p = {aa['srm_p']}).",
            "",
        ]
    ps = _read("process_study.json")
    if ps:
        n = len(ps["candidates"])
        good = sum(c["truly_good"] for c in ps["candidates"])
        harm = sum(c["truly_harmful"] for c in ps["candidates"])
        L += [
            "## How often the shipping process gets it wrong",
            "",
            f"{n} candidate releases, each a random change to production of the kind a team proposes. Their true effects were measured on {ps['truth_conversations']:,} conversations: {good} are truly better (resolution +0.5pp or more, no more hallucination, no unsafe action, cost within +30%), {harm} are harmful (resolution down 0.5pp or more, more hallucination, or any unsafe action), the rest make no material difference.",
            "",
            "| Policy | Shipped | Truly better | Harmful | Unsafe | Better ones missed | False-ship rate | True resolution gained |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for s in ps["score"]:
            L.append(
                f"| {s['policy']} | {s['shipped']} | {s['good_shipped']} | {s['harmful_shipped']} | {s['unsafe_shipped']} | {s['good_missed']} | {_pct(s['false_ship_rate'], 0)} | {s['true_resolution_gain_shipped_pp']:+.1f}pp |"
            )
        L += [
            "",
            "| Candidate | Change | True Δ resolution | True Δ hallucination | Unsafe | P0 | P1 | P2 | P3 | P4 | Stopped at |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        yes = lambda b: "ship" if b else "·"  # noqa: E731
        for c in ps["candidates"]:
            L.append(
                f"| {c['candidate']} | {c['change']} | {_pp(c['true_d_resolved'])} | {_pp(c['true_d_hallucinated'])} | {c['true_unsafe']} | {yes(c['P0 read 20'])} | {yes(c['P1 judges'])} | {yes(c['P2 calibrated'])} | {yes(c['P3 + A/B and rollout'])} | {yes(c.get('P4 backtest and rollout', False))} | {c['stopped_at']} |"
            )
        L.append("")
    od = _read("ops_drill.json")
    if od:
        L += [
            "## Production drill",
            "",
            "A fortnight of traffic with incidents injected, the same fortnight without them, alerts from observable data only.",
            "",
        ]
        names = [i["name"] for i in od["drills"][0]["incidents"]]
        L += [
            "| Incident | Minutes | " + " | ".join(f"Detected after (seed {s})" for s in od["seeds"]) + " | First alert |",
            "|---|---|" + "---|" * len(od["seeds"]) + "---|",
        ]
        for k, name in enumerate(names):
            row = [od["drills"][j]["incidents"][k] for j in range(len(od["seeds"]))]
            L.append(
                f"| {name} | {row[0]['minutes']} | "
                + " | ".join(f"{r['minutes_to_detect']} min" if r["detected"] else "missed" for r in row)
                + f" | {row[0]['first_alert']} |"
            )
        L += [
            "",
            "False alarms on the clean fortnight: "
            + ", ".join(str(d["false_alarms_clean_run"]) for d in od["drills"])
            + ". SLOs on the fortnight with incidents: "
            + ", ".join(
                f"{k} {_pct(v['achieved'], 2)} (budget used {_pct(v['budget_used'], 0)})" for k, v in od["drills"][0]["slo"].items()
            )
            + ".",
            "",
        ]
    fr = _read("cost_frontier.json")
    if fr:
        L += [
            "## Router threshold and cost",
            "",
            "Personalised release, same conversations, each escalation threshold and answer tier. Value = resolutions × €4 (a person handling it instead) − AI spend; only settings meeting the latency SLO are eligible.",
            "",
        ]
        L += [
            "| Escalate below | Answer tier | Resolution (observed) | AI cost / conv. | € per extra resolution | p95 latency | Meets latency SLO | Best |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in fr:
            e = r["eur_per_extra_resolution"]
            L.append(
                f"| {r['escalate_below']} | {r['answer_tier']} | {_pct(r['resolution_observed'])} | €{r['ai_cost_per_conversation_eur']:.4f} | {'' if e is None else f'€{e:.2f}'} | {r['latency_p95_s']}s | {'yes' if r['meets_latency_slo'] else 'no'} | {'best' if r['best_observed'] else ''} |"
            )
        L.append("")
    for v in ("v1", "v2", "v3"):
        ho = _read(f"heldout/{v}/first_run.json")
        if not ho:
            continue
        L += [
            f"## Held-out candidates {v} (first run)",
            "",
            f"Ten releases written by someone who saw only `docs/RELEASES.md`, run once on {ho['ran_at']} against `{ho.get('base', 'r1-prod')}` with process {ho.get('process', 'v1')}. See [heldout/{v}/FIRST_RUN.md](heldout/{v}/FIRST_RUN.md).",
            "",
        ]
        L += ["| Policy | Shipped | Truly better | Harmful | Unsafe | Better ones missed |", "|---|---|---|---|---|---|"]
        for s in ho["score"]:
            L.append(
                f"| {s['policy']} | {s['shipped']} | {s['good_shipped']} | {s['harmful_shipped']} | {s['unsafe_shipped']} | {s['good_missed']} |"
            )
        L.append("")
    g = _read("gate.json")
    if g:
        L += (
            ["## Gate", "", "| Check | Result | Detail |", "|---|---|---|"]
            + [f"| {c['check']} | {'pass' if c['passed'] else 'FAIL'} | {c['detail']} |" for c in g["checks"]]
            + [""]
        )
    text = "\n".join(L)
    (REPORTS / "EVALUATION.md").write_text(text)
    return text
